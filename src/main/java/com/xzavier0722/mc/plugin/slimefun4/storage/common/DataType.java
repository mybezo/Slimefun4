package com.xzavier0722.mc.plugin.slimefun4.storage.common;

/**
 * {@link DataType} is the type of Slimefun's database controller,
 * used to distinguish between different data storage types.
 */
public enum DataType {
    /**
     * Player profile, typically containing research progress, Backpacks, and other player-related data.
     */
    PLAYER_PROFILE,

    /**
     * Slimefun Block data
     */
    BLOCK_STORAGE
}
